import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
const root = 'benchmarks/runs/marketplace-diversity-v15-20260916';
const input = root + '/bubble-wrap/asset-evidence/b21769f37aebcdda6eb0ac61dc903a103236928c77b5367b382fb5511f1ec619.adaptation.json';
const out = root + '/syntax';
assert(!fs.existsSync(out));
fs.mkdirSync(out);
const compiler = path.resolve('research/tools/luau/luau-compile.exe');
assert(fs.existsSync(compiler));
const hash = x => createHash('sha256').update(x).digest('hex');
const originalBytes = fs.readFileSync(input);
const sidecar = JSON.parse(originalBytes);
const sources = [...sidecar.plan.replaceSources.map(x => ({ kind:'replace', ...x })), ...(sidecar.plan.addSources ?? []).map(x => ({ kind:'add', ...x }))];
assert(sources.length > 0);
const results = [];
for (let i = 0; i < sources.length; i++) {
  const source = sources[i];
  assert.equal(typeof source.source, 'string');
  const name = `${source.kind}-${i + 1}.luau`;
  fs.writeFileSync(out + '/' + name, source.source, {flag:'wx'});
  assert.equal(fs.readFileSync(out + '/' + name, 'utf8'), source.source);
  const run = spawnSync(compiler, [path.resolve(out, name)], {encoding:'utf8'});
  fs.writeFileSync(out + '/' + name + '.compile.txt', (run.stdout ?? '') + (run.stderr ?? ''), {flag:'wx'});
  results.push({file:name,kind:source.kind,sha256:hash(source.source),sourceBytes:Buffer.byteLength(source.source),exitCode:run.status,error:run.error?.message,syntaxPassed:run.status===0});
}
assert.deepEqual(fs.readFileSync(input), originalBytes);
const result = {at:new Date().toISOString(),adaptationSidecarHash:hash(originalBytes),compilerSha256:hash(fs.readFileSync(compiler)),results,allSyntaxPassed:results.every(x=>x.syntaxPassed),sourcesUnchanged:true,nativeOperations:0,runtimeBehaviorVerified:false,rawGamePass:false};
fs.writeFileSync(out + '/result.json', JSON.stringify(result,null,2), {flag:'wx'});
console.log(JSON.stringify(result));
assert(result.allSyntaxPassed);
