// Verify pinned evidence against both the collection hash and Git's blob hash.
// Reads downloaded source as bytes; never executes it.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '../evidence/open-source');
const read = p => JSON.parse(fs.readFileSync(p, 'utf8'));
const repositories = read(path.join(root, 'repositories.json'));
const manifest = read(path.join(root, 'files-manifest.json'));
const selected = read(path.resolve(__dirname, '../open-source-selection.json'));
const hash = (algorithm, bytes) => crypto.createHash(algorithm).update(bytes).digest('hex');
const expected = new Set(selected.flatMap(s => s.files.map(f => `${s.repo}:${f}`)));
const seen = new Set();
let totalBytes = 0;
const markdown = ['# Pinned open-source evidence', '',
 'Generated by `scripts/verify-open-source.cjs`. These are selected reference files, not full repository audits or installed dependencies. See [reuse decisions](../12-open-source-reuse.md).', ''];
for (const repo of repositories) {
 if (repo.error || repo.treeTruncated) throw Error('Incomplete repository: ' + JSON.stringify(repo));
 const tree = read(path.join(root, repo.requestedRepo.replace('/', '--'), 'tree.json'));
 if (tree.sha !== repo.commit) throw Error('Tree revision mismatch: ' + repo.repo);
 markdown.push(`## ${repo.repo}`, '', `Commit: \`${repo.commit}\`. Root license metadata: ${repo.licenseMetadata?.spdx_id || 'unknown'}. Commit date: ${repo.commitDate}.`, '');
 for (const entry of manifest.files.filter(f => f.repo === repo.requestedRepo)) {
  const key = `${entry.repo}:${entry.file}`;
  if (seen.has(key) || !expected.has(key)) throw Error('Unexpected or duplicate entry: ' + key);
  seen.add(key);
  if (entry.commit !== repo.commit) throw Error('File revision mismatch: ' + key);
  const local = path.resolve(root, entry.localPath);
  if (!local.startsWith(root + path.sep)) throw Error('Path outside evidence root');
  const bytes = fs.readFileSync(local);
  const blob = tree.tree.find(x => x.type === 'blob' && x.path === entry.file);
  const gitHash = hash('sha1', Buffer.concat([Buffer.from(`blob ${bytes.length}\0`), bytes]));
  if (entry.bytes !== bytes.length || hash('sha256', bytes) !== entry.sha256 || !blob || blob.sha !== gitHash) throw Error('Evidence hash mismatch: ' + key);
  totalBytes += bytes.length;
  const upstream = `https://github.com/${repo.repo}/blob/${repo.commit}/${entry.file}`;
  markdown.push(`- [${entry.file}](${upstream}) — [local copy](../evidence/open-source/${entry.localPath})`);
 }
 markdown.push('');
}
if (seen.size !== expected.size) throw Error('Missing selected evidence files');
const result = {verifiedAt: new Date().toISOString(), repositories: repositories.length, files: seen.size, totalBytes, sha256Verified: seen.size, gitBlobHashesVerified: seen.size};
fs.writeFileSync(path.resolve(__dirname, '../notes/open-source-index.md'), markdown.join('\n'));
fs.writeFileSync(path.join(root, 'verification.json'), JSON.stringify(result, null, 2));
console.log(JSON.stringify(result, null, 2));
