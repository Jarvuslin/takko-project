import fs from 'node:fs';
import path from 'node:path';
import {chromium} from '@playwright/test';
const dir=path.resolve('research/results/concept-live-v3/demo');
fs.mkdirSync(dir,{recursive:true});
const b=await chromium.launch({headless:true});
const context=await b.newContext({viewport:{width:1440,height:1000},recordVideo:{dir:path.join(dir,'raw'),size:{width:1440,height:1000}},reducedMotion:'reduce'});
const page=await context.newPage();
const timeline=[];
const started=Date.now();
const caption=(text)=>timeline.push({atSeconds:(Date.now()-started)/1000,text});
try{
  await page.goto('http://127.0.0.1:4348/');
  caption('Takko: start with an idea in your own words. This is a UI walkthrough, with no model call.');
  await page.getByLabel('Game idea').fill('I want a pet game. Should players rescue lost pets or battle with them? Help me choose.');
  await page.waitForTimeout(6500);
  await page.locator('.topbar').getByRole('button',{name:'Models',exact:true}).click();
  caption('Models is your reusable library. Add a provider and model once.');
  await page.waitForTimeout(4000);
  const add=page.getByRole('button',{name:/Add model/i}).first();
  await add.click();
  caption('Choose a provider, pick from its catalog, and enter the API key locally.');
  await page.waitForTimeout(6500);
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Presets',exact:true}).first().click();
  caption('Presets keep the model roles and spending limits together for reuse.');
  await page.waitForTimeout(6500);
  await page.getByRole('button',{name:'New project',exact:true}).click();
  await page.getByLabel('Game idea').fill('I want a pet game. Should players rescue lost pets or battle with them? Help me choose.');
  await page.getByRole('button',{name:'Create project',exact:true}).click();
  caption('Creating the project saves your idea. Shape my idea is the separate model action.');
  await page.getByRole('button',{name:'Shape my idea',exact:true}).waitFor();
  await page.waitForTimeout(6500);
  caption('Then review choices, answer or delegate, and approve the direction before planning. Live results follow only after a working key is connected.');
  await page.waitForTimeout(8000);
  await page.screenshot({path:path.join(dir,'intro-final.png'),fullPage:true});
  fs.writeFileSync(path.join(dir,'intro-timeline.json'),JSON.stringify({at:new Date().toISOString(),durationSeconds:(Date.now()-started)/1000,timeline,disclosure:'Actual UI recording, no inference. Empty demonstration workspace, no credentials.'},null,2));
  const video=page.video();await context.close();await video.saveAs(path.join(dir,'intro.webm'));
  console.log(JSON.stringify({video:path.join(dir,'intro.webm'),timeline:timeline.length}));
}finally{await b.close();}
