const key=windowsCredentialVault(path.join(process.env.APPDATA!,'Forge Desktop/provider-keys.dpapi'))!.read()['openrouter|https://openrouter.ai/api/v1'];
if(!key)throw Error('No saved OpenRouter credential');
const r=await fetch('https://openrouter.ai/api/v1/key',{headers:{Authorization:'Bearer '+key},signal:AbortSignal.timeout(15000),redirect:'error'});
if(!r.ok)throw Error('Balance HTTP '+r.status);
const {data}=await r.json();
const balance={at:new Date().toISOString(),limit:data.limit,remaining:data.limit_remaining,usage:data.usage};
fs.writeFileSync(path.join(output,process.argv.includes('--after')?'balance-after.json':'balance-before.json'),JSON.stringify(balance,null,2));
