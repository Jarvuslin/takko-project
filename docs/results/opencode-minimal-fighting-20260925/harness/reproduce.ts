check('Live planner produced 10 tasks',()=>assert.equal(p.spec!.tasks.length,10));
check('Every task has section tags but none covers theme',()=>assert.ok(p.spec!.tasks.every(t=>t.proposalSections?.length&&!t.proposalSections.includes('theme'))));
const original=JSON.stringify(p);
check('Actual saved plan reproduces exact bindProposalPlan rejection',()=>assert.throws(()=>bindProposalPlan(p),/Implementation dependency coverage is missing for proposal section: theme/));
check('Rejected binding does not mutate saved content',()=>assert.equal(JSON.stringify(p),original));
const clone=structuredClone(p);
clone.spec!.tasks.find(t=>t.id==='sceneEnvironment')!.proposalSections!.push('theme');
check('Diagnostic in-memory theme tag isolates this particular gate',()=>assert.doesNotThrow(()=>bindProposalPlan(clone)));
const needs=buildAssetNeeds(p);
check('Prior approved-asset binding helper accepts this real saved project offline',()=>assert.equal(needs.length,3));
check('Approved asset binding preserves exact existing need identities without duplication',()=>assert.deepEqual(needs.map(n=>n.id),p.spec!.assetNeeds!.map(n=>n.id)));
check('All three acquisition needs still link to existing requirements',()=>assert.ok(needs.every(n=>p.spec!.requirements.some(r=>r.id===n.requirementId))));
check('Raw brief discovery erroneously searches explicitly excluded VFX',()=>assert.ok(assetSearches({request:p.request,answers:{},briefChanges:[]}).some(g=>g.id==='effects')));
check('There is no generated code to evaluate for hit counter correctness',()=>assert.equal(p.artifact?.files.length??0,0));
check('No real OpenCode job ran',()=>assert.equal(p.opencodeRuns?.length??0,0));
check('Paid ledger remains within cap with no active reservations',()=>assert.ok(p.charges.reduce((n,c)=>n+c.chargedMicros,0)<=6000000&&p.reservedMicros===0));
const results={at:new Date().toISOString(),passed:checks.length,checks,limitations:'Offline checks against preserved real output. One in-memory diagnostic clone, never saved or used for paid continuation. No product fix, asset pipeline execution, OpenCode coding result, compilation or gameplay proof.'};
fs.writeFileSync(path.join(output,'offline-reproduction.json'),JSON.stringify(results,null,2));
