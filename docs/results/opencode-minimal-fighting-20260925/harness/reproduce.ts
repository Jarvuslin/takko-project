const output=path.resolve('docs/results/opencode-minimal-fighting-20260925');
const p:Project=JSON.parse(fs.readFileSync(path.join(output,'terminal-project.json'),'utf8'));
const checks:string[]=[];
function check(name:string,fn:()=>void){fn();checks.push(name);}
check('Saved fresh project used OpenCode',()=>assert.equal(p.executionMode,'opencode'));
check('Saved live failure is the missing theme coverage gate',()=>assert.equal(p.error,'Implementation dependency coverage is missing for proposal section: theme'));
